const normalize = (value: string) => value.trim().toLocaleLowerCase("ru").replace(/ё/g, "е").replace(/\s+/g, " ");

export function filterPenaltyReasons(query: string) {
  const words = normalize(query).split(" ").filter(Boolean);
  return penaltyReasons.filter(([code, label]) => words.every(word => normalize(`${label} ${code}`).includes(word)));
}

export function resolvePenaltyReason(value: string): { code: string; reason: string } {
  const text = value.trim();
  const known = penaltyReasons.find(([code, label]) => normalize(code) === normalize(text) || normalize(label) === normalize(text));
  return known ? { code: known[0], reason: known[1] } : { code: text ? "OTHER" : "", reason: text };
}
